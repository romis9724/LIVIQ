"""프롬프트 빌더 — 출처 강제·간결 응답 (규칙 1, docs/08 §2.3·§5).

시스템 프롬프트는 캐시 가능한 공통 접두부로 고정하고, 변동부(근거·질문)는 뒤에 둔다.
근거에는 [n] 번호를 붙여 LLM이 인용하게 하고, 후처리에서 [n] 실재를 검증한다.
"""


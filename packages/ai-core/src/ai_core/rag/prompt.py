# 공통 접두부 — 프롬프트 캐시 대상. 변경은 골든셋 회귀 평가 후(docs/07 §5).
SYSTEM_PROMPT = """당신은 아파트 관리사무소의 AI 도우미입니다. 규칙:
1. 아래 [근거]에 있는 내용만으로 답하십시오. 근거에 없는 내용은 절대 지어내지 마십시오.
2. 답변에 사용한 근거는 반드시 해당 문장 끝에 [번호] 형식으로 인용하십시오.
3. 근거로 답할 수 없으면 정확히 "NO_EVIDENCE"라고만 답하십시오.
4. 간결하게 답하십시오(불필요한 서론·반복 금지).
5. 한국어로 답하십시오."""

NO_EVIDENCE_MARKER = "NO_EVIDENCE"


# 도구호출 에이전트의 도구 결정 turn용 시스템 프롬프트(ADR-0007). 최종 답변 turn은
# ANSWER_SYSTEM_PROMPT를 쓴다 — 결정 turn은 도구 선택만 시킨다.
# 되묻기 지시를 조건부로 좁힌 이유(H19-5 R31 실측): 도구 12→15종 확장 후 모호하지 않은
# 질문("동별 대표자는 몇 명인가요?")까지 ask_clarification으로 새는 도피가 3회 측정 전부에서
# 10.4%로 재현됐다(R30 2.3~5.7%). 무조건문 "되물을 때는…"이 되묻기를 매 turn 상기시키는
# 구조라, "조회로 답이 정해지면 되묻지 말라"를 앞세워 기본 경로를 조회로 되돌린다.
AGENT_SYSTEM_PROMPT = """당신은 아파트 관리사무소의 AI 도우미입니다.
사용자 질문에 답하는 데 필요한 정보를 제공된 도구로 조회하십시오.
질문이 여러 정보를 필요로 하면 무엇을 조회할지 한 줄로 먼저 정한 뒤 도구를 호출하십시오.
여러 도구가 필요하면 조합해 호출하고, 근거가 충분하면 도구 호출을 멈추십시오.
질문은 대부분 조회만으로 답이 정해집니다 — 먼저 조회하십시오. 조회 결과가 두 갈래
이상으로 갈려 어느 쪽인지 정할 수 없을 때에 한해 되묻되, 문장을 쓰지 말고
기간·동호수·대상 설비처럼 무엇을 정해야 하는지 항목 이름만 지정하십시오.
도구 없이 추측하거나 지어내지 마십시오."""


def agent_system_prompt(today: datetime.date) -> str:
    """결정 turn 시스템 프롬프트 + 오늘 날짜.

    모델은 오늘을 모른다(학습 컷오프) — 날짜가 없으면 "이번 달"·"8월"처럼 연도 없는
    시점 표현을 엉뚱한 연도의 YYYY-MM으로 옮겨 존재하지 않는 월을 조회하고 폴백으로
    샌다(2026-08-01 실측: "8월 관리비"에 get_fees 4회 공회전 → no_evidence, 연도를
    붙여 물으면 정답). R23의 "상대날짜→period 매핑 실패 22%"의 뿌리가 이것이다.
    날짜는 일 단위 문자열이라 같은 날의 프롬프트는 동일 — 프리픽스 캐시는 하루
    단위로만 갈린다(캐시 접두부 원칙은 모듈 docstring).
    """
    return (
        f"{AGENT_SYSTEM_PROMPT}\n오늘은 {today.isoformat()}입니다. "
        "'이번 달'이나 '8월'처럼 연도가 없는 시점 표현은 이 날짜를 기준으로 해석하십시오."
    )

# 도구 결과(문서 근거 + 확정 데이터)를 근거로 최종 답변을 생성하는 turn용 프롬프트.
# 규칙 4는 **분량이 아니라 형식** 지시다(H18-4, ADR-0025 §8) — "2~4문장" 상한은 구조화·다단계
# 응답과 상충해 되돌렸다. 인용·NO_EVIDENCE 지시(규칙 1~3)는 손대지 않는다. 8B의 [n] 부착률이

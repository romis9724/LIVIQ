"""생활어 → 표준 시설·설비 명칭 사전 — 검색 질의 확장 (H20-7).

입주민은 "두꺼비집"이라 묻고 문서·시설 데이터는 "분전함"이라 적는다. bge-m3 임베딩은
이 둘을 이어주지 못해 검색이 빈다. 사전을 프롬프트에 넣는 방식은 기각했다 — 토큰 비용
(규칙 7)이고, 8B 파일럿은 프롬프트 문구 한 줄에 라우팅이 흔들린다(H15-2 R20 계열).
그래서 **임베딩용 텍스트만** 코드가 넓힌다. LLM에 가는 프롬프트·히스토리·도구 인자는
그대로다.

표준어는 전부 이 레포의 실제 데이터에서 뽑았다(2026-08-03 실측):
문서 코퍼스 `apps/api/scripts/data/documents_demo.py`(승강기 122·저수조 76·조명 16 등),
시설 시드 `facilities_kapt.py`(지하주차장 환기팬·옥내소화전), 민원 시드 `inquiries_demo.py`,
평면도 요소 코드 `liviq_db.codes_seed` PLAN_DEVICE_TYPE.

수록 기준 두 가지 — 어기면 검색이 나빠진다.
1. 생활어가 코퍼스에 거의 없고 표준어는 흔할 것. 코퍼스가 이미 쓰는 말(수도꼭지·방충망·
   결로·계량기)은 넣지 않는다. 넓힐 이유가 없다.
2. 표준어가 다른 계통과 겹치지 않을 것. "수도꼭지 → 수전"은 기각했다 — 이 단지에서
   `수전설비(2250kW·단일계약)`는 **전기** 수전이라 급수 질의를 전기실로 끌고 간다.
   "전구"도 뺐다("전구역"·"전구간"에 부분일치 — 코퍼스 10건).

세대 평면도 위치 매칭은 여기가 아니라 `tools/floor_plan_parser.ELEMENT_SYNONYMS`가
이미 접는다(두꺼비집 → device_type "분전함"). 그쪽 표준어는 평면도 요소 코드값이고
여기 표준어는 문서 어휘라 코도메인이 다르다 — 겹치는 항목은 의도된 중복이다.
"""

from __future__ import annotations

# 표준어(코퍼스 어휘) → 생활어들. 삽입 순서가 확장 접미사 순서(결정적).
FACILITY_SYNONYMS: dict[str, tuple[str, ...]] = {
    "분전함": ("두꺼비집", "두꺼비 집", "브레이커", "누전차단기"),
    "콘센트": ("플러그", "전기꽂이"),
    "승강기": ("엘리베이터", "엘베"),
    "조명": ("형광등", "전등"),
    "월패드": ("인터폰", "비디오폰", "도어폰"),
    "저수조": ("물탱크", "물 탱크"),
    "환기팬": ("환풍기",),
    "배수구": ("하수구",),
    "화재감지기": ("화재경보기", "연기감지기"),
    "도어록": ("도어락",),
}


def expand_query(text: str) -> str:
    """질의에 생활어가 있으면 표준어를 문말에 괄호로 덧붙인다(원문 보존).

    "두꺼비집이 어디야" → "두꺼비집이 어디야 (분전함)". 표준어가 이미 있으면 건너뛴다.
    치환이 아니라 덧붙임인 이유 — 원문 어휘도 검색 신호이고, 부분일치 오탐이 나도
    원문이 남아 있으면 피해가 잡음 수준에 그친다.
    """
    if not text:
        return text
    matched = [
        standard
        for standard, colloquials in FACILITY_SYNONYMS.items()
        if standard not in text and any(word in text for word in colloquials)
    ]
    if not matched:
        return text
    return f"{text} ({' '.join(matched)})"

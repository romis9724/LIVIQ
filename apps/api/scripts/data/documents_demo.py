def _won(amount: int) -> str:
    return f"{amount:,}원"


def _prev_period(date: datetime.date) -> str:
    year, month = (date.year, date.month - 1) if date.month > 1 else (date.year - 1, 12)
    return f"{year}년 {month}월"


def _attendees(round_: Round) -> tuple[Member, ...]:
    return tuple(m for m in COUNCIL if m.name not in round_.absentees)


def _meeting_sections(round_: Round) -> tuple[Section, ...]:
    """회의록 절 구성 — 개요·보고사항·안건별 논의와 의결·기타 토의·폐회."""
    present = _attendees(round_)
    quorum = len(COUNCIL) // 2 + 1
    attend_names = ", ".join(f"{m.name}({m.position})" for m in present)
    absent_names = ", ".join(round_.absentees) if round_.absentees else "없음"

    overview = Section(
        "1. 회의 개요",
        (
            f"일시: {round_.date.year}년 {round_.date.month}월 {round_.date.day}일 "
            f"{MEETING_TIME}   ·   장소: {MEETING_PLACE}",
            f"참석: 구성원 {len(COUNCIL)}명 중 {len(present)}명 — {attend_names}",
            f"불참: {absent_names}   ·   배석: {', '.join(STAFF_ATTENDEES)}",
            f"의결정족수 {quorum}명을 충족하여 회장이 개회를 선언하고 회의를 진행하였다. "
            "회의록은 관리사무소가 작성하고 회장과 감사가 확인한다.",
        ),
    )

    report = Section(
        "2. 보고사항",
        (
            f"{_prev_period(round_.date)} 관리비 부과 총액은 {_won(round_.fee_total)}이며 "
            f"{TOTAL_HOUSEHOLDS}세대에 부과되었다. 미납은 {round_.unpaid_units}세대 "
            f"{_won(round_.unpaid_amount)}으로, 3개월 이상 장기 미납 세대에는 개별 안내문을 "
            "발송하였다.",
            f"민원은 {round_.inquiries_in}건 접수되어 {round_.inquiries_done}건을 처리하였고 "
            f"{round_.inquiries_in - round_.inquiries_done}건이 처리 중이다. 접수 경로별로는 "
            "관리사무소 방문과 입주민 앱 접수가 대부분을 차지한다.",
            round_.report_extra,
        ),
    )

    agenda_sections = []
    for index, agenda in enumerate(round_.agendas, start=1):
        yes, no, abstain = agenda.votes
        verdict = "가결" if yes > no else "부결"
        vote_line = (
            f"의결: 참석 {len(present)}명 중 찬성 {yes}명, 반대 {no}명, 기권 {abstain}명으로 "
            f"{verdict}되었다. {agenda.resolution}"
        )
        heading = f"3-{index}. 제{index}호 안건 — {agenda.title}"
        agenda_sections.append(Section(heading, (*agenda.discussion, vote_line)))

    closing = Section(
        "5. 폐회 및 확인",
        (
            "이상으로 모든 안건을 심의하고 회장이 폐회를 선언하였다. 의결사항은 관리주체가 "
            "집행하며 집행 결과는 다음 정기회의에서 보고한다.",
            f"작성: 관리사무소   ·   확인: 입주자대표회의 회장 {COUNCIL[0].name}, "
            f"감사 {COUNCIL[1].name}",
        ),
    )
    return (overview, report, *agenda_sections, Section("4. 기타 토의사항", round_.misc), closing)


def _meeting_doc(round_: Round) -> DemoDoc:
    year, month = round_.date.year, round_.date.month
    topics = ", ".join(a.title.removesuffix("(안)") for a in round_.agendas)
    return DemoDoc(
        title=f"{year}년 제{month}차 정기 입주자대표회의 회의록",
        category=CATEGORY_MINUTES,
        visibility=VISIBILITY_RESIDENT,
        filename=f"{year}-{month:02d}_정기_입주자대표회의_회의록.pdf",
        body=(
            f"{year}년 {month}월 {round_.date.day}일 개최한 정기 입주자대표회의 회의록입니다. "
            f"주요 안건: {topics}."
        ),
        doc_date=round_.date,
        sections=_meeting_sections(round_),
    )


